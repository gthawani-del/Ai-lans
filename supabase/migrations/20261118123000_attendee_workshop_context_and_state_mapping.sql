CREATE OR REPLACE FUNCTION public.map_attendee_city_region() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $fn$
DECLARE key text; area text;
BEGIN
 IF TG_OP='UPDATE' AND NEW.city IS NOT DISTINCT FROM OLD.city
    AND NEW.country IS NOT DISTINCT FROM OLD.country
    AND NEW.state_mapping_status='manual' THEN RETURN NEW; END IF;
 NEW.state_region:=NULL; NEW.state_mapping_source:='reference'; NEW.state_mapping_status:='not_mapped';
 IF lower(trim(coalesce(NEW.country,''))) NOT IN ('india','in') THEN RETURN NEW; END IF;
 key:=lower(trim(regexp_replace(coalesce(NEW.city,''),'[[:space:]]+',' ','g')));
 IF key IN ('aurangabad','bilaspur','hamirpur','fatehpur','raigarh','rampur','sultanpur') THEN
   NEW.state_mapping_status:='needs_review'; RETURN NEW;
 END IF;
 SELECT ref.state_region INTO area FROM public.attendee_city_region_reference ref WHERE ref.city_key=key;
 IF area IS NOT NULL THEN NEW.state_region:=area; NEW.state_mapping_status:='matched'; END IF;
 RETURN NEW;
END $fn$;
